//! Freehand strokes: brushes stamp coverage into a [`StrokeMask`], which is then composited onto a
//! layer with a color and opacity. Keeping coverage separate means a stroke never darkens where it
//! overlaps itself, matching Paint's behaviour with the opacity slider.

use crate::color::{Color, mul_div255};
use crate::geom::{PixelRect, Point};
use crate::noise::{Rng, hash2, value_noise};
use tiny_skia::Pixmap;

/// Freehand drawing tools.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum BrushKind {
    Pencil,
    Eraser,
    Brush,
    CalligraphyBrush,
    CalligraphyPen,
    Airbrush,
    Oil,
    Crayon,
    Marker,
    NaturalPencil,
    Watercolor,
}

impl BrushKind {
    /// The nine brushes of the "Brushes" menu, in Paint's order.
    pub const BRUSHES: [BrushKind; 9] = [
        BrushKind::Brush,
        BrushKind::CalligraphyBrush,
        BrushKind::CalligraphyPen,
        BrushKind::Airbrush,
        BrushKind::Oil,
        BrushKind::Crayon,
        BrushKind::Marker,
        BrushKind::NaturalPencil,
        BrushKind::Watercolor,
    ];

    /// Texture applied to the coverage of this brush.
    pub fn texture(self) -> Texture {
        match self {
            BrushKind::Oil => Texture::Oil,
            BrushKind::Crayon => Texture::Crayon,
            BrushKind::Marker => Texture::Marker,
            BrushKind::NaturalPencil => Texture::NaturalPencil,
            BrushKind::Watercolor => Texture::Watercolor,
            _ => Texture::Solid,
        }
    }

    /// Distance between stamps relative to the brush size.
    fn spacing(self, size: f32) -> f32 {
        let f = match self {
            BrushKind::Pencil | BrushKind::Eraser => 0.25,
            BrushKind::Airbrush => 0.35,
            BrushKind::Oil => 0.08,
            _ => 0.12,
        };
        (size * f).max(0.5)
    }
}

/// A coverage texture shared by brushes and shape outline/fill styles.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Texture {
    Solid,
    Crayon,
    Marker,
    Oil,
    NaturalPencil,
    Watercolor,
}

impl Texture {
    /// Coverage multiplier in `[0, 1]` at a canvas pixel.
    pub fn factor(self, x: i32, y: i32) -> f32 {
        let (fx, fy) = (x as f32, y as f32);
        match self {
            Texture::Solid => 1.0,
            Texture::Marker => 0.85,
            Texture::Crayon => {
                let grain = hash2(x, y, 11) * 0.55 + value_noise(fx, fy, 3.0, 5) * 0.45;
                smoothstep(0.32, 0.62, grain)
            }
            Texture::NaturalPencil => {
                let grain = hash2(x, y, 23) * 0.6 + value_noise(fx, fy, 2.0, 9) * 0.4;
                0.25 + 0.65 * smoothstep(0.2, 0.75, grain)
            }
            Texture::Oil => {
                // Streaks along the stroke are generated by the brush itself; for shapes use a soft
                // irregular texture.
                0.55 + 0.45 * value_noise(fx, fy, 2.5, 13)
            }
            Texture::Watercolor => 0.32 + 0.3 * value_noise(fx, fy, 14.0, 17) + 0.08 * value_noise(fx, fy, 3.0, 3),
        }
    }
}

fn smoothstep(e0: f32, e1: f32, x: f32) -> f32 {
    let t = ((x - e0) / (e1 - e0)).clamp(0.0, 1.0);
    t * t * (3.0 - 2.0 * t)
}

/// A canvas-sized coverage buffer.
#[derive(Clone, Debug)]
pub struct StrokeMask {
    width: u32,
    height: u32,
    data: Vec<u8>,
    bounds: PixelRect,
}

impl StrokeMask {
    pub fn new(width: u32, height: u32) -> Self {
        Self { width, height, data: vec![0; width as usize * height as usize], bounds: PixelRect::EMPTY }
    }

    pub fn width(&self) -> u32 {
        self.width
    }

    pub fn height(&self) -> u32 {
        self.height
    }

    /// Area that contains non zero coverage.
    pub fn bounds(&self) -> PixelRect {
        self.bounds
    }

    #[inline]
    pub fn get(&self, x: i32, y: i32) -> u8 {
        if x < 0 || y < 0 || x >= self.width as i32 || y >= self.height as i32 {
            return 0;
        }
        self.data[y as usize * self.width as usize + x as usize]
    }

    /// Raises coverage at a pixel to at least `v`.
    #[inline]
    pub fn put_max(&mut self, x: i32, y: i32, v: u8) {
        if v == 0 || x < 0 || y < 0 || x >= self.width as i32 || y >= self.height as i32 {
            return;
        }
        let i = y as usize * self.width as usize + x as usize;
        if self.data[i] < v {
            self.data[i] = v;
        }
        self.bounds = self.bounds.union(&PixelRect::from_xywh(x, y, 1, 1));
    }

    /// Marks `r` as possibly containing coverage (used after bulk writes).
    pub fn include(&mut self, r: PixelRect) {
        self.bounds = self.bounds.union(&r.clamp_to(self.width, self.height));
    }

    pub fn row_mut(&mut self, y: i32) -> &mut [u8] {
        let w = self.width as usize;
        &mut self.data[y as usize * w..(y as usize + 1) * w]
    }

    pub fn clear(&mut self) {
        let b = self.bounds;
        for y in b.y0..b.y1 {
            let row = self.row_mut(y);
            row[b.x0 as usize..b.x1 as usize].fill(0);
        }
        self.bounds = PixelRect::EMPTY;
    }

    /// Multiplies coverage by a texture.
    pub fn apply_texture(&mut self, texture: Texture) {
        if texture == Texture::Solid {
            return;
        }
        let b = self.bounds;
        for y in b.y0..b.y1 {
            for x in b.x0..b.x1 {
                let i = y as usize * self.width as usize + x as usize;
                let v = self.data[i];
                if v != 0 {
                    self.data[i] = (f32::from(v) * texture.factor(x, y)).round() as u8;
                }
            }
        }
    }

    /// Copies a tiny-skia mask (same size) into this mask using max.
    pub fn merge_skia_mask(&mut self, mask: &tiny_skia::Mask, region: PixelRect) {
        let region = region.clamp_to(self.width.min(mask.width()), self.height.min(mask.height()));
        let mw = mask.width() as usize;
        let src = mask.data();
        for y in region.y0..region.y1 {
            for x in region.x0..region.x1 {
                let v = src[y as usize * mw + x as usize];
                if v != 0 {
                    let i = y as usize * self.width as usize + x as usize;
                    self.data[i] = self.data[i].max(v);
                }
            }
        }
        self.include(region);
    }
}

/// How coverage is applied to the layer.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum BlendMode {
    /// Paint `color` over the layer.
    Over,
    /// Remove alpha from the layer (eraser).
    Erase,
}

/// Composites `mask` onto `region` (a pixmap covering `region_rect` in canvas coordinates).
pub fn apply_mask(region: &mut Pixmap, region_rect: PixelRect, mask: &StrokeMask, color: Color, opacity: f32, mode: BlendMode) {
    let area = region_rect.intersect(&mask.bounds());
    if area.is_empty() {
        return;
    }
    let op = (opacity.clamp(0.0, 1.0) * 255.0).round() as u16;
    let pm = color.premultiplied();
    let rw = region.width() as usize;
    let data = region.data_mut();
    for y in area.y0..area.y1 {
        let ry = (y - region_rect.y0) as usize;
        for x in area.x0..area.x1 {
            let m = mask.get(x, y);
            if m == 0 {
                continue;
            }
            let k = u16::from(mul_div255(u16::from(m), op));
            let i = (ry * rw + (x - region_rect.x0) as usize) * 4;
            let px = &mut data[i..i + 4];
            match mode {
                BlendMode::Over => {
                    let sa = mul_div255(u16::from(pm[3]), k);
                    let inv = 255 - u16::from(sa);
                    for c in 0..3 {
                        let s = mul_div255(u16::from(pm[c]), k);
                        px[c] = s.saturating_add(mul_div255(u16::from(px[c]), inv));
                    }
                    px[3] = sa.saturating_add(mul_div255(u16::from(px[3]), inv));
                }
                BlendMode::Erase => {
                    let keep = 255 - k;
                    for c in px.iter_mut() {
                        *c = mul_div255(u16::from(*c), keep);
                    }
                }
            }
        }
    }
}

/// An in-progress freehand stroke.
#[derive(Clone, Debug)]
pub struct Stroke {
    pub kind: BrushKind,
    pub size: f32,
    mask: StrokeMask,
    last: Option<Point>,
    carry: f32,
    travelled: f32,
    rng: Rng,
    bristles: [f32; 16],
    dir: (f32, f32),
    texture: Texture,
}

impl Stroke {
    pub fn new(kind: BrushKind, size: f32, width: u32, height: u32, seed: u32) -> Self {
        let mut rng = Rng::new(seed);
        let mut bristles = [0.0; 16];
        for b in &mut bristles {
            *b = 0.35 + 0.65 * rng.next_f32();
        }
        Self {
            kind,
            size: size.max(1.0),
            mask: StrokeMask::new(width, height),
            last: None,
            carry: 0.0,
            travelled: 0.0,
            rng,
            bristles,
            dir: (1.0, 0.0),
            // Oil streaks come from its bristles; the others multiply coverage by a paper texture.
            // Because max(a*t, b*t) == max(a, b)*t, texturing each stamp equals texturing the
            // finished stroke, so previews are exact.
            texture: if kind == BrushKind::Oil { Texture::Solid } else { kind.texture() },
        }
    }

    pub fn mask(&self) -> &StrokeMask {
        &self.mask
    }

    /// Finalizes the stroke and returns its coverage.
    pub fn finish(self) -> StrokeMask {
        self.mask
    }

    /// Writes textured coverage.
    #[inline]
    fn put(&mut self, x: i32, y: i32, v: u8) {
        let v = if self.texture == Texture::Solid { v } else { (f32::from(v) * self.texture.factor(x, y)) as u8 };
        self.mask.put_max(x, y, v);
    }

    /// Extends the stroke to `p`; returns the canvas area that changed.
    pub fn add_point(&mut self, p: Point) -> PixelRect {
        let before = self.mask.bounds();
        match self.last {
            None => {
                self.stamp(p);
                self.last = Some(p);
            }
            Some(last) => {
                let dist = last.distance(p);
                if dist > 0.0 {
                    let (dx, dy) = ((p.x - last.x) / dist, (p.y - last.y) / dist);
                    // Smooth the direction so oil streaks bend gracefully.
                    self.dir = normalize(self.dir.0 * 0.6 + dx * 0.4, self.dir.1 * 0.6 + dy * 0.4);
                }
                if matches!(self.kind, BrushKind::Pencil) {
                    self.pencil_line(last, p);
                } else {
                    let step = self.kind.spacing(self.size);
                    let mut t = step - self.carry;
                    while t <= dist {
                        let q = last.lerp(p, t / dist);
                        self.stamp(q);
                        t += step;
                    }
                    self.carry = dist - (t - step);
                }
                self.travelled += dist;
                self.last = Some(p);
            }
        }
        let after = self.mask.bounds();
        if after == before {
            // Airbrush dots may land inside the old bounds.
            PixelRect::enclosing(p.x - self.size, p.y - self.size, p.x + self.size, p.y + self.size)
                .clamp_to(self.mask.width(), self.mask.height())
        } else {
            after
        }
    }

    /// Called periodically while the pointer is held still (airbrush keeps spraying).
    pub fn hold(&mut self) -> Option<PixelRect> {
        if self.kind != BrushKind::Airbrush {
            return None;
        }
        let p = self.last?;
        self.stamp(p);
        Some(PixelRect::enclosing(p.x - self.size, p.y - self.size, p.x + self.size, p.y + self.size))
    }

    fn pencil_line(&mut self, a: Point, b: Point) {
        let (mut x0, mut y0) = a.floor_i();
        let (x1, y1) = b.floor_i();
        let dx = (x1 - x0).abs();
        let dy = -(y1 - y0).abs();
        let sx = if x0 < x1 { 1 } else { -1 };
        let sy = if y0 < y1 { 1 } else { -1 };
        let mut err = dx + dy;
        loop {
            self.hard_stamp(x0, y0);
            if x0 == x1 && y0 == y1 {
                break;
            }
            let e2 = 2 * err;
            if e2 >= dy {
                err += dy;
                x0 += sx;
            }
            if e2 <= dx {
                err += dx;
                y0 += sy;
            }
        }
    }

    /// Aliased square/round stamp used by the pencil and the eraser.
    fn hard_stamp(&mut self, cx: i32, cy: i32) {
        let n = self.size.round().max(1.0) as i32;
        let off = (n - 1) / 2;
        let round = self.kind == BrushKind::Pencil && n > 2;
        let r2 = (n as f32 / 2.0).powi(2);
        for y in 0..n {
            for x in 0..n {
                if round {
                    let (fx, fy) = (x as f32 + 0.5 - n as f32 / 2.0, y as f32 + 0.5 - n as f32 / 2.0);
                    if fx * fx + fy * fy > r2 {
                        continue;
                    }
                }
                self.put(cx - off + x, cy - off + y, 255);
            }
        }
    }

    fn stamp(&mut self, p: Point) {
        let r = self.size / 2.0;
        match self.kind {
            BrushKind::Pencil | BrushKind::Eraser => {
                let (x, y) = p.floor_i();
                self.hard_stamp(x, y);
            }
            BrushKind::Brush | BrushKind::Crayon | BrushKind::NaturalPencil | BrushKind::Marker => {
                let r = if self.kind == BrushKind::NaturalPencil { (r * 0.6).max(0.6) } else { r };
                self.round(p, r, |_, _, cov| cov);
            }
            BrushKind::Watercolor => self.round(p, r, |_, t, _| (1.0 - t * t).sqrt()),
            BrushKind::CalligraphyBrush => self.ellipse(p, r, (r * 0.3).max(0.75), true),
            BrushKind::CalligraphyPen => self.ellipse(p, r, (r * 0.12).max(0.6), false),
            BrushKind::Airbrush => {
                let count = ((self.size * self.size) / 12.0).clamp(3.0, 400.0) as usize;
                for _ in 0..count {
                    let a = self.rng.next_f32() * std::f32::consts::TAU;
                    let d = self.rng.next_f32().sqrt() * r;
                    let (x, y) = ((p.x + a.cos() * d).floor() as i32, (p.y + a.sin() * d).floor() as i32);
                    self.put(x, y, 255);
                }
            }
            BrushKind::Oil => {
                // Bristles: coverage depends on the offset across the stroke direction, which
                // produces streaks; the paint slowly runs out along the stroke.
                let (nx, ny) = (-self.dir.1, self.dir.0);
                let fade = (1.0 - self.travelled / (self.size * 60.0 + 200.0)).max(0.55);
                let bristles = self.bristles;
                self.round(p, r, move |(dx, dy), _, cov| {
                    let across = ((dx * nx + dy * ny) / r.max(0.5)).clamp(-1.0, 0.999);
                    let idx = (((across + 1.0) / 2.0) * bristles.len() as f32) as usize;
                    cov * fade * bristles[idx.min(bristles.len() - 1)]
                });
            }
        }
    }

    /// Anti-aliased round stamp. `f(offset from center, normalized distance, coverage)` shapes it.
    fn round(&mut self, p: Point, r: f32, f: impl Fn((f32, f32), f32, f32) -> f32) {
        let r = r.max(0.5);
        let x0 = (p.x - r - 1.0).floor() as i32;
        let x1 = (p.x + r + 1.0).ceil() as i32;
        let y0 = (p.y - r - 1.0).floor() as i32;
        let y1 = (p.y + r + 1.0).ceil() as i32;
        for y in y0..y1 {
            for x in x0..x1 {
                let (dx, dy) = (x as f32 + 0.5 - p.x, y as f32 + 0.5 - p.y);
                let d = (dx * dx + dy * dy).sqrt();
                let cov = (r - d + 0.5).clamp(0.0, 1.0);
                if cov > 0.0 {
                    let v = f((dx, dy), (d / r).min(1.0), cov).clamp(0.0, 1.0);
                    self.put(x, y, (v * 255.0) as u8);
                }
            }
        }
    }

    /// Elliptic nib at 45°, used by the calligraphy tools.
    fn ellipse(&mut self, p: Point, major: f32, minor: f32, soft: bool) {
        let (s, c) = (std::f32::consts::FRAC_1_SQRT_2, std::f32::consts::FRAC_1_SQRT_2);
        let ext = major + 1.0;
        let x0 = (p.x - ext).floor() as i32;
        let x1 = (p.x + ext).ceil() as i32;
        let y0 = (p.y - ext).floor() as i32;
        let y1 = (p.y + ext).ceil() as i32;
        for y in y0..y1 {
            for x in x0..x1 {
                let (dx, dy) = (x as f32 + 0.5 - p.x, y as f32 + 0.5 - p.y);
                let u = dx * c + dy * s;
                let v = -dx * s + dy * c;
                let k = ((u / major).powi(2) + (v / minor).powi(2)).sqrt();
                // Approximate signed distance in pixels along the minor axis for anti-aliasing.
                let edge = (1.0 - k) * minor + 0.5;
                let cov = if soft { edge.clamp(0.0, 1.0) * 0.95 } else { edge.clamp(0.0, 1.0) };
                if cov > 0.0 {
                    self.put(x, y, (cov * 255.0) as u8);
                }
            }
        }
    }
}

fn normalize(x: f32, y: f32) -> (f32, f32) {
    let l = (x * x + y * y).sqrt();
    if l == 0.0 { (1.0, 0.0) } else { (x / l, y / l) }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::raster;

    #[test]
    fn pencil_draws_continuous_line() {
        let mut s = Stroke::new(BrushKind::Pencil, 1.0, 20, 20, 1);
        s.add_point(Point::new(1.5, 1.5));
        s.add_point(Point::new(15.5, 9.5));
        let m = s.finish();
        assert_eq!(m.get(1, 1), 255);
        assert_eq!(m.get(15, 9), 255);
        // Every column between the ends is covered exactly once in a 1px line.
        for x in 1..=15 {
            assert_eq!((0..20).filter(|&y| m.get(x, y) == 255).count(), 1, "column {x}");
        }
    }

    #[test]
    fn brushes_cover_their_path() {
        for kind in BrushKind::BRUSHES {
            let mut s = Stroke::new(kind, 10.0, 64, 64, 3);
            s.add_point(Point::new(10.0, 32.0));
            s.add_point(Point::new(50.0, 32.0));
            for _ in 0..5 {
                s.hold();
            }
            let m = s.finish();
            let b = m.bounds();
            assert!(!b.is_empty(), "{kind:?}");
            assert!(b.x0 <= 12 && b.x1 >= 48, "{kind:?} {b:?}");
        }
    }

    #[test]
    fn apply_over_and_erase() {
        let mut layer = raster::pixmap(4, 4);
        let mut m = StrokeMask::new(4, 4);
        m.put_max(1, 1, 255);
        apply_mask(&mut layer, PixelRect::from_size(4, 4), &m, Color::rgb(255, 0, 0), 1.0, BlendMode::Over);
        assert_eq!(raster::get_pixel(&layer, 1, 1), Some(Color::rgb(255, 0, 0)));
        apply_mask(&mut layer, PixelRect::from_size(4, 4), &m, Color::BLACK, 0.5, BlendMode::Erase);
        let a = layer.pixel(1, 1).unwrap().alpha();
        assert!((126..=129).contains(&a), "{a}");
        m.clear();
        assert!(m.bounds().is_empty());
        assert_eq!(m.get(1, 1), 0);
    }

    #[test]
    fn apply_on_offset_region() {
        let mut region = raster::pixmap(2, 2);
        let mut m = StrokeMask::new(10, 10);
        m.put_max(5, 5, 255);
        apply_mask(&mut region, PixelRect::new(4, 4, 6, 6), &m, Color::BLACK, 1.0, BlendMode::Over);
        assert_eq!(region.pixel(1, 1).unwrap().alpha(), 255);
        assert_eq!(region.pixel(0, 0).unwrap().alpha(), 0);
    }
}
